/** 重複を除いた文字の並び（Web フォントに含める文字） */
export function fontText(): string {
  return [...new Set(FIXED_TITLE_PHRASES.join('').replace(/\s/g, ''))].join('');
}

/** Google Fonts の CSS を取る URL。text= で文字を絞る（1 本のリクエスト） */
export function titleFontHref(): string {
  const text = encodeURIComponent(fontText());
  return `https://fonts.googleapis.com/css2?family=Shippori+Mincho+B1:wght@500;700&display=swap&text=${text}`;
}
